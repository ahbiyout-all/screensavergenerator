import { ScrMakerConfig } from '../types/screensaverMaker';

/**
 * Generates pure C# WinForms source code that compiles into a native Windows .scr screensaver.
 * It strictly supports standard Windows command-line arguments:
 *   /s - Fullscreen run
 *   /c - Settings dialog
 *   /p <HWND> - Preview box in Windows Display Properties
 */
export function generateCSharpSource(config: ScrMakerConfig): string {
  const safeName = config.outputName.replace(/[^a-zA-Z0-9_]/g, '') || 'MyScreensaver';
  const hexToColor = (hex: string) => {
    // Convert #RRGGBB to Color.FromArgb(...)
    const clean = hex.replace('#', '');
    const r = parseInt(clean.substring(0, 2), 16) || 0;
    const g = parseInt(clean.substring(2, 4), 16) || 0;
    const b = parseInt(clean.substring(4, 6), 16) || 0;
    return `Color.FromArgb(${r}, ${g}, ${b})`;
  };

  const primaryColor = hexToColor(
    config.template === 'matrix' ? config.matrixCharColor :
    config.template === 'starfield' ? config.starColor :
    config.template === 'clock' ? config.clockFontColor :
    config.template === 'bouncing' ? config.bouncingTextColor :
    config.waveColor1
  );

  return `// ====================================================================
// Windows Screen Saver (.scr) Source Code
// Generated by Screensaver Manager Studio
// Target: .NET Framework 4.0+ (Compiled via native csc.exe)
// ====================================================================

using System;
using System.Drawing;
using System.Drawing.Drawing2D;
using System.Windows.Forms;
using System.Runtime.InteropServices;
using System.Collections.Generic;

namespace ${safeName}Screensaver
{
    static class Program
    {
        [DllImport("user32.dll")]
        static extern IntPtr SetParent(IntPtr hWndChild, IntPtr hWndNewParent);

        [DllImport("user32.dll")]
        static extern int SetWindowLong(IntPtr hWnd, int nIndex, IntPtr dwNewLong);

        [DllImport("user32.dll", SetLastError = true)]
        static extern int GetWindowLong(IntPtr hWnd, int nIndex);

        [DllImport("user32.dll")]
        static extern bool GetClientRect(IntPtr hWnd, out Rectangle lpRect);

        [DllImport("shcore.dll")]
        static extern int SetProcessDpiAwareness(int awareness);

        [DllImport("user32.dll")]
        static extern bool SetProcessDPIAware();

        [STAThread]
        static void Main(string[] args)
        {
            // 1. Multi-Monitor Per-Monitor DPI Awareness (Prevents coordinate drift & blur on mixed DPI screens)
            try
            {
                SetProcessDpiAwareness(2); // PROCESS_PER_MONITOR_DPI_AWARE
            }
            catch
            {
                try { SetProcessDPIAware(); } catch { }
            }

            Application.EnableVisualStyles();
            Application.SetCompatibleTextRenderingDefault(false);

            if (args.Length > 0)
            {
                string firstArgument = args[0].ToLower().Trim();
                string secondArgument = null;

                // Handle cases where argument is '/c:12345'
                if (firstArgument.Length > 2)
                {
                    secondArgument = firstArgument.Substring(3).Trim();
                    firstArgument = firstArgument.Substring(0, 2);
                }
                else if (args.Length > 1)
                {
                    secondArgument = args[1];
                }

                if (firstArgument == "/c")
                {
                    // Configuration mode
                    ShowConfiguration();
                    return;
                }
                else if (firstArgument == "/p")
                {
                    // Preview mode
                    if (secondArgument != null)
                    {
                        IntPtr previewWndHandle = new IntPtr(long.Parse(secondArgument));
                        Application.Run(new ScreensaverForm(previewWndHandle));
                        return;
                    }
                }
                else if (firstArgument == "/s")
                {
                    // Fullscreen screensaver mode
                    ShowScreensaver();
                    return;
                }
            }

            // Default fallback if double-clicked without args
            ShowScreensaver();
        }

        static void ShowScreensaver()
        {
            bool isAllScreens = ${config.multiMonitorMode === 'all_screens' ? 'true' : 'false'};

            foreach (Screen screen in Screen.AllScreens)
            {
                bool shouldAnimate = screen.Primary || isAllScreens;
                ScreensaverForm screensaver = new ScreensaverForm(screen.Bounds, shouldAnimate);
                screensaver.Show();
            }
            Application.Run();
        }

        static void ShowConfiguration()
        {
            MessageBox.Show(
                "${config.title}\\n\\nTemplate: ${config.template.toUpperCase()}\\nMulti-Monitor: ${config.multiMonitorMode === 'all_screens' ? 'All Displays' : 'Primary Only (Secondary Blackout)'}\\nSettings configured in Screensaver Studio.\\n\\nCreated for Windows Screensaver Manager.",
                "Screensaver Configuration",
                MessageBoxButtons.OK,
                MessageBoxIcon.Information
            );
        }
    }

    public class ScreensaverForm : Form
    {
        private Timer renderTimer;
        private Point mouseLocation;
        private bool isPreviewMode = false;
        private Random rand = new Random();

        // Template specific variables
${getTemplateVariables(config)}

        // Fullscreen constructor (Multi-Monitor aware)
        public ScreensaverForm(Rectangle bounds, bool shouldAnimate = true)
        {
            InitializeComponent();
            this.StartPosition = FormStartPosition.Manual;
            this.Bounds = bounds;
            this.TopMost = true;
            this.FormBorderStyle = FormBorderStyle.None;
            // CRITICAL: Keep FormWindowState.Normal! FormWindowState.Maximized forces WinForms back to Primary screen!
            this.WindowState = FormWindowState.Normal;
            Cursor.Hide();

            if (shouldAnimate)
            {
                InitEngine();
            }
            else
            {
                // Pure blackout screen for secondary monitors (Zero CPU/GPU load, OLED Burn-in protection)
                this.BackColor = Color.Black;
            }
        }

        // Preview constructor
        public ScreensaverForm(IntPtr previewHandle)
        {
            InitializeComponent();
            this.isPreviewMode = true;

            // Set parent window to the preview box
            SetParent(this.Handle, previewHandle);
            SetWindowLong(this.Handle, -16, new IntPtr(GetWindowLong(this.Handle, -16) | 0x40000000));

            Rectangle parentRect;
            GetClientRect(previewHandle, out parentRect);
            this.Size = parentRect.Size;
            this.Location = new Point(0, 0);

            InitEngine();
        }

        private void InitializeComponent()
        {
            this.DoubleBuffered = true;
            this.SetStyle(ControlStyles.AllPaintingInWmPaint | ControlStyles.UserPaint | ControlStyles.OptimizedDoubleBuffer, true);
            this.BackColor = Color.Black;
            this.StartPosition = FormStartPosition.Manual;
            this.KeyPreview = true;

            this.MouseMove += ScreensaverForm_MouseMove;
            this.KeyDown += ScreensaverForm_KeyDown;
            this.MouseDown += ScreensaverForm_MouseDown;
            this.Paint += ScreensaverForm_Paint;
        }

        private void InitEngine()
        {
${getTemplateInitCode(config)}

            renderTimer = new Timer();
            renderTimer.Interval = 16; // ~60 FPS
            renderTimer.Tick += (s, e) => {
${getTemplateUpdateCode(config)}
                this.Invalidate();
            };
            renderTimer.Start();
        }

        private void ScreensaverForm_Paint(object sender, PaintEventArgs e)
        {
            Graphics g = e.Graphics;
            g.SmoothingMode = SmoothingMode.AntiAlias;
            g.TextRenderingHint = System.Drawing.Text.TextRenderingHint.ClearTypeGridFit;

${getTemplateRenderCode(config, primaryColor)}
        }

        private void ScreensaverForm_MouseMove(object sender, MouseEventArgs e)
        {
            if (isPreviewMode) return;
            ${config.exitOnMouseMove ? `if (!mouseLocation.IsEmpty)
            {
                // Multi-monitor threshold: ignore tiny jitter when moving across DPI scale barriers
                if (Math.Abs(mouseLocation.X - e.X) > 15 || Math.Abs(mouseLocation.Y - e.Y) > 15)
                {
                    Application.Exit();
                }
            }
            mouseLocation = e.Location;` : '// Mouse move exit disabled'}
        }

        private void ScreensaverForm_KeyDown(object sender, KeyEventArgs e)
        {
            if (isPreviewMode) return;
            ${config.exitOnKeyPress ? 'Application.Exit();' : '// Key exit disabled'}
        }

        private void ScreensaverForm_MouseDown(object sender, MouseEventArgs e)
        {
            if (isPreviewMode) return;
            Application.Exit();
        }

        [DllImport("user32.dll")]
        static extern IntPtr SetParent(IntPtr hWndChild, IntPtr hWndNewParent);

        [DllImport("user32.dll")]
        static extern int SetWindowLong(IntPtr hWnd, int nIndex, IntPtr dwNewLong);

        [DllImport("user32.dll", SetLastError = true)]
        static extern int GetWindowLong(IntPtr hWnd, int nIndex);

        [DllImport("user32.dll")]
        static extern bool GetClientRect(IntPtr hWnd, out Rectangle lpRect);
    }
}
`;
}

function getTemplateVariables(config: ScrMakerConfig): string {
  switch (config.template) {
    case 'matrix':
      return `        private int[] dropPositions;
        private string matrixChars = "${config.matrixCustomText.replace(/"/g, '\\"')}";
        private int charSize = ${config.matrixCharSize};
        private int speed = ${config.matrixSpeed};`;

    case 'starfield':
      return `        private class Star { public float X, Y, Z; }
        private List<Star> stars = new List<Star>();
        private int starCount = ${config.starCount};
        private float speed = ${config.starSpeed}f;`;

    case 'clock':
      return `        private string message = "${config.clockCustomMessage.replace(/"/g, '\\"')}";
        private Font clockFont = new Font("Segoe UI", ${config.clockFontSize}, FontStyle.Bold);
        private Font subFont = new Font("Segoe UI", 20, FontStyle.Regular);`;

    case 'neon_waves':
      return `        private float wavePhase = 0f;
        private int waveCount = ${config.waveCount};
        private float waveSpeed = ${config.waveSpeed * 0.02}f;`;

    case 'bouncing':
      return `        private float posX = 100f, posY = 100f;
        private float velX = ${config.bouncingSpeed}f, velY = ${config.bouncingSpeed * 0.8}f;
        private string text = "${config.bouncingText.replace(/"/g, '\\"')}";
        private Font bounceFont = new Font("Segoe UI Black", ${config.bouncingSize}, FontStyle.Bold);`;
  }
}

function getTemplateInitCode(config: ScrMakerConfig): string {
  switch (config.template) {
    case 'matrix':
      return `            int cols = Math.Max(10, this.Width / charSize);
            dropPositions = new int[cols];
            for (int i = 0; i < cols; i++)
            {
                dropPositions[i] = rand.Next(-50, 0);
            }`;

    case 'starfield':
      return `            stars.Clear();
            for (int i = 0; i < starCount; i++)
            {
                stars.Add(new Star {
                    X = rand.Next(-1000, 1000),
                    Y = rand.Next(-1000, 1000),
                    Z = rand.Next(1, 1000)
                });
            }`;

    case 'clock':
      return `            // Clock initialized`;

    case 'neon_waves':
      return `            wavePhase = 0f;`;

    case 'bouncing':
      return `            posX = 50f;
            posY = 50f;`;
  }
}

function getTemplateUpdateCode(config: ScrMakerConfig): string {
  switch (config.template) {
    case 'matrix':
      return `                if (dropPositions == null) return;
                for (int i = 0; i < dropPositions.Length; i++)
                {
                    dropPositions[i] += speed / 2 + 1;
                    if (dropPositions[i] * charSize > this.Height && rand.Next(0, 10) > 3)
                    {
                        dropPositions[i] = 0;
                    }
                }`;

    case 'starfield':
      return `                for (int i = 0; i < stars.Count; i++)
                {
                    stars[i].Z -= speed * 2;
                    if (stars[i].Z <= 0)
                    {
                        stars[i].X = rand.Next(-1000, 1000);
                        stars[i].Y = rand.Next(-1000, 1000);
                        stars[i].Z = 1000;
                    }
                }`;

    case 'clock':
      return `                // Re-render clock frame`;

    case 'neon_waves':
      return `                wavePhase += waveSpeed;`;

    case 'bouncing':
      return `                posX += velX;
                posY += velY;
                if (posX <= 0 || posX + 200 >= this.Width) velX = -velX;
                if (posY <= 0 || posY + 60 >= this.Height) velY = -velY;`;
  }
}

function getTemplateRenderCode(config: ScrMakerConfig, primaryColor: string): string {
  switch (config.template) {
    case 'matrix':
      return `            using (Font f = new Font("Consolas", charSize, FontStyle.Bold))
            using (SolidBrush textBrush = new SolidBrush(${primaryColor}))
            using (SolidBrush headBrush = new SolidBrush(Color.White))
            {
                if (dropPositions == null) return;
                for (int i = 0; i < dropPositions.Length; i++)
                {
                    int x = i * charSize;
                    int y = dropPositions[i] * charSize;
                    
                    // Leading bright character
                    char headChar = matrixChars[rand.Next(0, matrixChars.Length)];
                    g.DrawString(headChar.ToString(), f, headBrush, x, y);

                    // Trailing faint characters
                    for (int j = 1; j < 8; j++)
                    {
                        int trailY = y - j * charSize;
                        if (trailY >= 0 && trailY <= this.Height)
                        {
                            char trailChar = matrixChars[(i + j) % matrixChars.Length];
                            int alpha = Math.Max(20, 255 - j * 32);
                            using (SolidBrush fadeBrush = new SolidBrush(Color.FromArgb(alpha, ${primaryColor}.R, ${primaryColor}.G, ${primaryColor}.B)))
                            {
                                g.DrawString(trailChar.ToString(), f, fadeBrush, x, trailY);
                            }
                        }
                    }
                }
            }`;

    case 'starfield':
      return `            float cx = this.Width / 2f;
            float cy = this.Height / 2f;
            using (SolidBrush starBrush = new SolidBrush(${primaryColor}))
            {
                foreach (var star in stars)
                {
                    float k = 500f / star.Z;
                    float px = star.X * k + cx;
                    float py = star.Y * k + cy;
                    float size = Math.Max(1.5f, (1000f - star.Z) / 180f);

                    if (px >= 0 && px < this.Width && py >= 0 && py < this.Height)
                    {
                        g.FillEllipse(starBrush, px - size / 2, py - size / 2, size, size);
                        ${config.starWarpEffect ? `if (star.Z < 700) {
                            float prevK = 500f / (star.Z + 15);
                            float prevPx = star.X * prevK + cx;
                            float prevPy = star.Y * prevK + cy;
                            using (Pen warpPen = new Pen(Color.FromArgb(120, ${primaryColor}.R, ${primaryColor}.G, ${primaryColor}.B), size * 0.6f))
                            {
                                g.DrawLine(warpPen, prevPx, prevPy, px, py);
                            }
                        }` : ''}
                    }
                }
            }`;

    case 'clock':
      return `            DateTime now = DateTime.Now;
            string timeStr = ${config.clockFormat24h ? `now.ToString("HH:mm${config.clockShowSeconds ? ':ss' : ''}")` : `now.ToString("hh:mm${config.clockShowSeconds ? ':ss' : ''} tt")`};
            string dateStr = ${config.clockShowDate ? `now.ToString("yyyy년 MM월 dd일 dddd")` : '""'};

            SizeF timeSize = g.MeasureString(timeStr, clockFont);
            float timeX = (this.Width - timeSize.Width) / 2f;
            float timeY = (this.Height - timeSize.Height) / 2f - 40;

            using (SolidBrush textBrush = new SolidBrush(${primaryColor}))
            using (SolidBrush subBrush = new SolidBrush(Color.FromArgb(180, 200, 220)))
            {
                g.DrawString(timeStr, clockFont, textBrush, timeX, timeY);

                if (!string.IsNullOrEmpty(dateStr))
                {
                    SizeF dateSize = g.MeasureString(dateStr, subFont);
                    g.DrawString(dateStr, subFont, subBrush, (this.Width - dateSize.Width) / 2f, timeY + timeSize.Height + 10);
                }

                if (!string.IsNullOrEmpty(message))
                {
                    SizeF msgSize = g.MeasureString(message, subFont);
                    g.DrawString(message, subFont, textBrush, (this.Width - msgSize.Width) / 2f, timeY + timeSize.Height + 50);
                }
            }`;

    case 'neon_waves':
      return `            int h = this.Height;
            int w = this.Width;
            for (int wave = 0; wave < waveCount; wave++)
            {
                List<PointF> points = new List<PointF>();
                float baseOffset = (wave - waveCount / 2f) * 60f;
                for (int x = 0; x <= w; x += 15)
                {
                    float y = (h / 2f) + baseOffset + (float)Math.Sin(x * 0.008f + wavePhase + wave * 0.8f) * 80f;
                    points.Add(new PointF(x, y));
                }

                int alpha = Math.Min(255, 120 + wave * 25);
                using (Pen wavePen = new Pen(Color.FromArgb(alpha, ${primaryColor}.R, ${primaryColor}.G, ${primaryColor}.B), 3f))
                {
                    g.DrawCurve(wavePen, points.ToArray());
                }
            }`;

    case 'bouncing':
      return `            using (SolidBrush textBrush = new SolidBrush(${primaryColor}))
            using (Pen glowPen = new Pen(Color.FromArgb(100, ${primaryColor}.R, ${primaryColor}.G, ${primaryColor}.B), 4f))
            {
                g.DrawString(text, bounceFont, textBrush, posX, posY);
            }`;
  }
}

/**
 * Generates Build_Scr.bat that uses Windows's built-in csc.exe compiler.
 * Works on 100% of Windows machines without needing Visual Studio or .NET SDK!
 */
export function generateBuildBat(config: ScrMakerConfig): string {
  const safeName = config.outputName.replace(/[^a-zA-Z0-9_]/g, '') || 'MyScreensaver';
  return `@echo off
chcp 65001 >nul
title Windows Screensaver Builder (.scr) - ${safeName}
cls

echo =====================================================================
echo  [Windows Screensaver .scr Auto Compiler]
echo  Target: ${safeName}.scr
echo  Engine: Native Microsoft .NET Framework C# Compiler (csc.exe)
echo =====================================================================
echo.

:: 1. Search for csc.exe in Windows Framework directories
set CSC=
if exist "%windir%\\Microsoft.NET\\Framework64\\v4.0.30319\\csc.exe" (
    set "CSC=%windir%\\Microsoft.NET\\Framework64\\v4.0.30319\\csc.exe"
) else if exist "%windir%\\Microsoft.NET\\Framework\\v4.0.30319\\csc.exe" (
    set "CSC=%windir%\\Microsoft.NET\\Framework\\v4.0.30319\\csc.exe"
) else (
    echo [ERROR] Could not find csc.exe in standard .NET Framework directories.
    echo Please make sure .NET Framework 4.0 or later is installed.
    pause
    exit /b 1
)

echo [*] Found C# Compiler: %CSC%
echo [*] Compiling source: ${safeName}.cs ...

:: 2. Compile to Win32 GUI Executable (.scr extension is a PE Win32 executable)
"%CSC%" /target:winexe /optimize+ /platform:anycpu /out:"${safeName}.scr" /reference:System.Windows.Forms.dll,System.Drawing.dll "${safeName}.cs"

if %ERRORLEVEL% equ 0 (
    echo.
    echo =====================================================================
    echo  [SUCCESS] Screensaver successfully built: ${safeName}.scr
    echo =====================================================================
    echo.
    echo  * Double-click "${safeName}.scr" to test fullscreen.
    echo  * Right-click "${safeName}.scr" and choose 'Install' to set as your Windows screensaver.
    echo  * Or run "Install.bat" to install into Windows System32 directory.
    echo.
) else (
    echo.
    echo [ERROR] Compilation failed with error code %ERRORLEVEL%.
    echo Check the error messages above.
)

pause
`;
}

/**
 * Generates Install.bat to easily install or test the .scr file
 */
export function generateInstallBat(config: ScrMakerConfig): string {
  const safeName = config.outputName.replace(/[^a-zA-Z0-9_]/g, '') || 'MyScreensaver';
  return `@echo off
chcp 65001 >nul
title Screensaver Installer - ${safeName}.scr
cls

echo =====================================================================
echo  [Windows Screensaver .scr Installer]
echo  Target: ${safeName}.scr
echo =====================================================================
echo.

if not exist "${safeName}.scr" (
    echo [!] "${safeName}.scr" not found. Running Build_Scr.bat first...
    call Build_Scr.bat
    if not exist "${safeName}.scr" (
        echo [ERROR] Build failed or cancelled. Exiting.
        pause
        exit /b 1
    )
)

echo [1] Test ScreenSaver Fullscreen now
echo [2] Install to Windows System32 (Requires Administrator)
echo [3] Open Windows Screen Saver Settings Dialog
echo [4] Exit
echo.
set /p choice="Select an option (1-4): "

if "%choice%"=="1" (
    start "" "${safeName}.scr" /s
    exit /b 0
)

if "%choice%"=="2" (
    echo.
    echo Copying to %windir%\\System32\\${safeName}.scr ...
    copy /y "${safeName}.scr" "%windir%\\System32\\${safeName}.scr"
    if %ERRORLEVEL% equ 0 (
        echo [OK] Successfully installed! Setting as default screensaver...
        reg add "HKEY_CURRENT_USER\\Control Panel\\Desktop" /v SCRNSAVE.EXE /t REG_SZ /d "%windir%\\System32\\${safeName}.scr" /f
        echo [OK] Default screensaver updated!
    ) else (
        echo [!] Administrator privileges required. Right-click and choose "Run as Administrator".
    )
    pause
    exit /b 0
)

if "%choice%"=="3" (
    control desk.cpl,,@screensaver
    exit /b 0
)

exit /b 0
`;
}

